def encontrar_similares_tfidf(palabra_objetivo, n=5):
    if palabra_objetivo not in word2idx:
        print(f"La palabra '{palabra_objetivo}' no está en el vocabulario (quizás se filtró o no existe).")
        return

    # a) Obtener el vector de la palabra objetivo
    idx = word2idx[palabra_objetivo]
    target_vector = word_vectors[idx]

    # b) Calcular similitud coseno contra TODAS las otras palabras
    # cosine_similarity espera matrices, así que pasamos (1, docs) vs (vocab, docs)
    # Nota: word_vectors es (vocab, docs) sparse matrix
    similitudes = cosine_similarity(target_vector, word_vectors)

    # c) Ordenar resultados
    # Flatten convierte la matriz de resultados en un array plano
    indices_ordenados = np.argsort(similitudes.flatten())[::-1]

    print(f"\n--- Términos más similares a '{palabra_objetivo}' (vía TF-IDF) ---")
    # Empezamos en 1 porque el 0 es la palabra misma (similitud 1.0)
    count = 0
    for i in indices_ordenados:
        word = vocabulario[i]
        score = similitudes[0, i]

        if word == palabra_objetivo:
            continue

        print(f"Palabra: {word} | Similitud: {score:.4f}")
        count += 1
        if count >= n:
            break

