"""NDCG penaliza el orden: "A diferencia de Precision@K, que es una métrica binaria (¿está el ítem relevante en la lista? Sí/No) y le da igual si está en la posición 1 o en la 5, el NDCG (Normalized Discounted Cumulative Gain) valora la posición. Utiliza un descuento logarítmico en el denominador. Si el algoritmo coloca la canción favorita del usuario (relevancia real) en la posición 5, el 'score' que gana es mucho menor que si la hubiera puesto en la posición 1. NDCG entiende que el usuario presta mucha más atención a los primeros resultados."

##4.2 Evaluación de Ranking (NDCG)
"""

import numpy as np

def calculate_ndcg(recom_list, ground_truth, k=5):
    """
    recom_list: Lista de items recomendados por el modelo (ordenados por score).
    ground_truth: Set o lista de items que el usuario realmente consumió.
    """

    # 1. Calcular DCG (Ganancia Acumulada con Descuento)
    dcg = 0
    for i in range(min(len(recom_list), k)):
        item = recom_list[i]

        # Si el item es relevante, relevancia = 1, si no = 0
        rel = 1 if item in ground_truth else 0

        # Fórmula de descuento logarítmico: rel / log2(posición + 1)
        # Nota: i empieza en 0, por eso usamos i+2 para el logaritmo (log en base 2 de 2 es pos 1)
        dcg += rel / np.log2(i + 2)

    # 2. Calcular IDCG (Ideal DCG)
    # Es el DCG perfecto: si hubiéramos puesto todos los items relevantes primero
    num_relevantes = len(set(recom_list) & set(ground_truth)) # Intersección
    idcg = 0
    for i in range(min(num_relevantes, k)):
        idcg += 1 / np.log2(i + 2)
    # Evitar división por cero
    if idcg == 0:
        return 0.0

    return dcg / idcg

