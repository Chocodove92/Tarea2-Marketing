movie_meta.info()

margin_map = dict(zip(movie_meta['movie_id'], movie_meta['margin_category']))

def rerank_por_margen(item_ids, scores, margin_map):
    nuevos_scores = []

    for item, score in zip(item_ids, scores):
        # Obtener categoría (asumimos 'Low' si no existe info)
        categoria = margin_map.get(item, 'Low')

        factor = 1.2 if categoria == 'High' else 0.9

        nuevos_scores.append((item, score * factor))

    # Re-ordenar la lista basada en los nuevos scores (de mayor a menor)

    recomendaciones_rerankeadas = sorted(nuevos_scores, key=lambda x: x[1], reverse=True)

    # Devolver solo los IDs ordenados
    return [x[0] for x in recomendaciones_rerankeadas]

